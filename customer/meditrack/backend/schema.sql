-- MediTrack HMS v3.4 schema (Medisoft Solutions Inc., 2011; Ohio, USA)
-- NOTE: original vendor documentation lost. Column meanings reverse-engineered by CityForward IT (2019).
-- Legacy traits kept on purpose: cryptic names, no foreign keys, dates stored as TEXT ('YYYY-MM-DD HH:MM'),
-- short status codes, free-text notes.
-- Runs as the application owner (role "meditrack") in database "meditrack".

DROP TABLE IF EXISTS DR_MST, USR_MST, PT_MST, IP_ADM_DTL, IP_DIAG_DTL, IP_PROC_DTL, LAB_RSLT, PHR_ISS_DTL, CLN_NOTE,
                     PT_DOC, IP_DSCH_SUMM, PYR_AUTH_DTL, SYS_EXT_LNK, SYS_AUDIT CASCADE;

CREATE TABLE DR_MST (          -- clinician master
    DR_ID      TEXT PRIMARY KEY,
    DR_NM      TEXT,
    DR_SPCL    TEXT,           -- speciality
    DR_NPI     TEXT            -- National Provider Identifier (10 digits)
);

CREATE TABLE USR_MST (         -- staff logins (the EHR's own user master; no SSO in v3.4)
    USR_ID     TEXT PRIMARY KEY,
    USR_NM     TEXT,
    ROLE_CD    TEXT,           -- ATTENDING | RESIDENT | NURSE | PA_COORD | HIM_CODER | IT_ADMIN
    UNIT_CD    TEXT,           -- ward the user works on, or ALL
    DR_ID      TEXT,           -- link to DR_MST for clinicians
    IS_ACTV    INTEGER
);

CREATE TABLE PT_MST (          -- patient master
    PT_ID    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MRN      TEXT UNIQUE,      -- medical record number
    PT_NM    TEXT,
    PT_DOB   TEXT,             -- 'YYYY-MM-DD'
    PT_AGE   INTEGER,          -- age at last admission (cached by the vendor)
    PT_SEX   TEXT,             -- M | F
    PT_PHN   TEXT,
    PT_ADDR  TEXT,
    PT_CITY  TEXT,
    PT_ST    TEXT,
    PT_ZIP   TEXT,
    PT_SSN   TEXT              -- synthetic 9xx-xx-xxxx numbers only
);

CREATE TABLE IP_ADM_DTL (      -- visit register: in-patient admissions, plus ED / office / home-health visits (added 2014)
    IP_NO        TEXT PRIMARY KEY,
    PT_ID        INTEGER,
    ADM_DT       TEXT,
    WRD_CD       TEXT,         -- unit, e.g. 4W-CARD
    BED_NO       TEXT,
    DR_ID        TEXT,         -- attending
    PAY_MODE     TEXT,         -- SELF_PAY | INSURED
    PYR_NM       TEXT,         -- payer / health plan
    MBR_ID       TEXT,         -- member id
    ADM_RSN      TEXT,
    STS          TEXT,         -- ADM = admitted, DA = discharge advised, DSCH = discharged, CLS = closed (non-admission visit)
    DSCH_ADV_DT  TEXT,
    DSCH_DT      TEXT,
    DSCH_DISP    TEXT,         -- HOME | HOME_HEALTH | SNF | REHAB | EXPIRED
    ENC_CLS      TEXT,         -- IMP | ED | OP | HH | VR   (IP_NO prefix follows the class: IP, ED, OP, HH, VR)
    ENC_TYP      TEXT          -- visit type, free text
);

CREATE TABLE IP_DIAG_DTL (
    ID         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IP_NO      TEXT,
    ICD_CD     TEXT,           -- ICD-10-CM
    DIAG_DESC  TEXT,
    DIAG_TYP   TEXT            -- PROV | FINAL
);

CREATE TABLE IP_PROC_DTL (
    ID         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IP_NO      TEXT,
    PROC_CD    TEXT,
    PROC_SYS   TEXT,           -- SCT (SNOMED CT) | HCPCS
    PROC_DESC  TEXT,
    PROC_DT    TEXT,
    SURGEON    TEXT
);

CREATE TABLE LAB_RSLT (        -- fed by the lab system over HL7 v2 (ORU^R01)
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IP_NO     TEXT,
    TST_NM    TEXT,
    LOINC_CD  TEXT,
    RSLT_VAL  TEXT,
    UOM       TEXT,
    REF_RNG   TEXT,
    FLG       TEXT,            -- H | L | blank
    RSLT_DT   TEXT,
    STS       TEXT             -- FINAL | PENDING
);

CREATE TABLE PHR_ISS_DTL (     -- pharmacy issue
    ID       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IP_NO    TEXT,
    DRUG_NM  TEXT,
    RXN_CD   TEXT,             -- RxNorm
    DOSE     TEXT,
    FREQ     TEXT,
    ROUTE    TEXT,
    DUR      TEXT,
    ISS_TYP  TEXT,             -- HOME (list at admission) | INPATIENT | DISCHARGE | OUTPT
    MED_STS  TEXT              -- ACTIVE | DONE
);

CREATE TABLE CLN_NOTE (        -- clinical notes, free text
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IP_NO     TEXT,
    NOTE_DT   TEXT,
    NOTE_TYP  TEXT,            -- DR | NRS
    AUTH      TEXT,
    NOTE_TXT  TEXT
);

CREATE TABLE PT_DOC (          -- scanned / uploaded documents
    DOC_ID   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IP_NO    TEXT,
    DOC_TYP  TEXT,             -- CATH_RPT | DEVICE_LOG | OP_NOTE | CONSENT | ID_PROOF | INS_CARD | DSCHSUMM | ...
    FILE_NM  TEXT,
    UPL_DT   TEXT,
    UPL_BY   TEXT
);

CREATE TABLE IP_DSCH_SUMM (    -- manually typed discharge summary
    IP_NO    TEXT PRIMARY KEY,
    SUMM_TXT TEXT,
    CRT_BY   TEXT,
    CRT_DT   TEXT
);

CREATE TABLE PYR_AUTH_DTL (    -- payer authorization / claim responses
    ID       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IP_NO    TEXT,
    SUBM_DT  TEXT,
    AUTH_STS TEXT,             -- APPROVED | QUERY | DENIED
    QRY_RSN  TEXT,
    RESP_DT  TEXT
);

CREATE TABLE SYS_EXT_LNK (     -- admin-configurable external links (added v3.1, 2016)
    LNK_ID   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LNK_LBL  TEXT,
    LNK_URL  TEXT,             -- {IP_NO} and {MRN} placeholders supported
    DISP_MD  TEXT,             -- LINK = new window | TAB = embedded page (v3.2) | SMART = SMART on FHIR app, EHR launch (v3.4)
    IS_ACTV  INTEGER,
    CRT_BY   TEXT,
    CRT_DT   TEXT
);

CREATE TABLE SYS_AUDIT (
    ID    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TS    TEXT,
    USR   TEXT,
    ACTN  TEXT,
    REF   TEXT
);
