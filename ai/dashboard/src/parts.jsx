import { useEffect, useState } from 'react'
import { api } from './api.js'

export function Banner({ data, session, onAbout }) {
  const p = data.patient
  return (
    <header className="banner">
      <div className="who">
        <h1>{p.name}</h1>
        <span className="meta">{p.age} y {p.sex === 'M' ? 'male' : 'female'} · {p.location || p.unit || 'no bed'} · {p.payer || 'self-pay'}</span>
        <span className="meta">Admitted {p.admitted} · day {p.los_days}{p.status === 'in-progress' ? '' : ' · discharged'} · account {p.encounter}</span>
      </div>
      <div className="right">
        <span className="pill ai" title="Generated by software for a clinician to review">AI-assisted · clinician review required</span>
        <button className="link" onClick={onAbout}>About this tool</button>
        <span className="user">{session.user || 'Signed in'}{session.role ? ` · ${session.role.toLowerCase().replace('_', ' ')}` : ''}</span>
      </div>
    </header>
  )
}

export function Chip({ id, onClick }) {
  return <button className="chip" onClick={onClick} title="Show the source">{id}</button>
}

export function Why({ why, iss, onClose }) {
  if (!why) return <aside className="why empty"><h2>Why am I seeing this?</h2><p>Select a flag, a source chip like <span className="chip static">E3</span> or a timeline item to see the rule or the exact chart text behind it.</p><p className="muted">Everything the assistant says is traceable to the record. If it cannot be traced, it is not shown.</p></aside>
  return (
    <aside className="why" aria-live="polite">
      <div className="why-head"><h2>Why am I seeing this?</h2><button className="x" onClick={onClose} aria-label="Close">×</button></div>
      <h3>{why.title}</h3>
      {why.rule && <div className="rule"><b>Rule:</b> {why.rule}</div>}
      {why.sources?.map((s, i) => (
        <figure key={i} className="source">
          <figcaption>{s.label || s.ref}</figcaption>
          <blockquote>{s.text}</blockquote>
          <div className="ref"><code>{s.ref}</code><button className="link" onClick={() => navigator.clipboard?.writeText(`${iss}/${s.ref}`)}>Copy FHIR link</button></div>
        </figure>))}
      {why.next && <div className="next"><b>Suggested next step:</b> {why.next}</div>}
      <p className="muted small">{why.footer || 'Sources are shown verbatim from the EHR. Confirm anything that matters in the full record.'}</p>
    </aside>
  )
}

export function About({ onClose }) {
  const [a, setA] = useState(null)
  useEffect(() => { api('/about').then(setA).catch(() => setA({ intended_use: 'Unavailable', method: '', limitations: [] })) }, [])
  return (
    <div className="modal" role="dialog" aria-modal="true" aria-label="About this tool" onClick={onClose}>
      <div className="card" onClick={(e) => e.stopPropagation()}>
        <h1>About this tool</h1>
        {a ? <><h3>Intended use</h3><p>{a.intended_use}</p><h3>How it works</h3><p>{a.method}</p><h3>Limits</h3><ul>{a.limitations.map((l, i) => <li key={i}>{l}</li>)}</ul></> : <p>Loading…</p>}
        <button className="primary" onClick={onClose}>Close</button>
      </div>
    </div>
  )
}

export function ErrorNote({ error }) {
  return error ? <div className="error" role="alert">{error}</div> : null
}

export function useAction() {
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState('')
  const run = async (fn) => { setBusy(true); setError(''); try { return await fn() } catch (e) { setError(e.message); return null } finally { setBusy(false) } }
  return { busy, error, run, setError }
}
